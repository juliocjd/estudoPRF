import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { openStudyDatabase } from '../src/db/open-study-database.mjs';

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_JSON = path.join(ROOT_DIR, 'data', 'essay_dossiers', 'essay_theme_dossiers_v1.json');
const VALID_VERIFICACAO = new Set(['primaria', 'secundaria', 'curadoria']);

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = parseArgs(process.argv.slice(2));
  const report = await importEssayThemeDossiers({
    dbPath: args.db || 'questoes-prf.sqlite',
    dbClient: args['db-client'] || '',
    jsonPath: path.resolve(ROOT_DIR, args.json || DEFAULT_JSON),
    dryRun: Boolean(args['dry-run'])
  });
  console.log(JSON.stringify(report, null, 2));
  process.exit(report.anchorsMissing.length ? 1 : 0);
}

export async function importEssayThemeDossiers({ dbPath, dbClient, jsonPath, dryRun }) {
  const payload = JSON.parse(await fsp.readFile(jsonPath, 'utf8'));
  const dossiers = Array.isArray(payload.dossiers) ? payload.dossiers : [];
  if (!dossiers.length) throw new Error('Nenhum dossiê no arquivo de seed.');

  const { client, db } = openStudyDatabase({ dbPath, client: dbClient });
  ensureDossierSchema(db, client);

  // Toda âncora precisa existir no compêndio. É esse gate que impede
  // um section_key inventado de virar "fundamento legal" na tela.
  const anchorsMissing = [];
  const dataWarnings = [];
  const selectSection = db.prepare('SELECT section_key, is_revoked FROM law_compendium_sections WHERE section_key = ?');

  for (const dossier of dossiers) {
    for (const anchor of dossier.ancorasLegais || []) {
      const row = selectSection.get(anchor.sectionKey);
      if (!row) anchorsMissing.push({ themeId: dossier.themeId, sectionKey: anchor.sectionKey, problema: 'inexistente' });
      else if (row.is_revoked) anchorsMissing.push({ themeId: dossier.themeId, sectionKey: anchor.sectionKey, problema: 'revogado' });
    }
    for (const dado of dossier.dados || []) {
      if (!VALID_VERIFICACAO.has(dado.verificacao)) {
        dataWarnings.push({ themeId: dossier.themeId, afirmacao: dado.afirmacao, problema: `verificacao inválida: ${dado.verificacao}` });
      }
      if (!dado.url || !dado.ano) {
        dataWarnings.push({ themeId: dossier.themeId, afirmacao: dado.afirmacao, problema: 'dado sem url ou ano' });
      }
    }
  }

  if (anchorsMissing.length) {
    return { client, dryRun, imported: 0, anchorsMissing, dataWarnings, erro: 'Âncoras inválidas — nada foi importado.' };
  }

  let imported = 0;
  if (!dryRun) {
    const upsert = db.prepare(`
      INSERT INTO essay_theme_dossiers (theme_id, version, dossier_json, updated_at)
      VALUES (?, ?, ?, CURRENT_TIMESTAMP)
      ON CONFLICT (theme_id) DO UPDATE SET
        version = excluded.version,
        dossier_json = excluded.dossier_json,
        updated_at = CURRENT_TIMESTAMP
    `);
    for (const dossier of dossiers) {
      upsert.run(dossier.themeId, payload.version || 'v1', JSON.stringify(dossier));
      imported += 1;
    }
  }

  return {
    client,
    dryRun: Boolean(dryRun),
    imported,
    temas: dossiers.map((d) => d.themeId),
    anchorsMissing,
    dataWarnings
  };
}

function ensureDossierSchema(db, client) {
  if (client === 'postgres') {
    db.exec(`
      CREATE TABLE IF NOT EXISTS essay_theme_dossiers (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        theme_id text NOT NULL UNIQUE,
        version text NOT NULL,
        dossier_json text NOT NULL,
        updated_at timestamptz DEFAULT CURRENT_TIMESTAMP
      )
    `);
    return;
  }
  db.exec(`
    CREATE TABLE IF NOT EXISTS essay_theme_dossiers (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      theme_id TEXT NOT NULL UNIQUE,
      version TEXT NOT NULL,
      dossier_json TEXT NOT NULL,
      updated_at TEXT DEFAULT CURRENT_TIMESTAMP
    )
  `);
}

function parseArgs(argv) {
  const args = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (!arg.startsWith('--')) continue;
    const key = arg.slice(2);
    const next = argv[index + 1];
    if (!next || next.startsWith('--')) {
      args[key] = true;
      continue;
    }
    args[key] = next;
    index += 1;
  }
  return args;
}
